/**
 * Helper to retrieve a translated string using dot-notation.
 * Falls back to English if the German translation is absent.
 */
export function getTranslation(
    keyPath: string,
    locale: Locale = "en",
    params?: Record<string, string | number>
): string {
    const keys = keyPath.split(".");
    let current: any = translations[locale] || translations.en;
    let fallback: any = translations.en;

    for (const key of keys) {
        if (current && typeof current === "object" && key in current) {
            current = current[key];
        } else {
            current = undefined;
        }

        if (fallback && typeof fallback === "object" && key in fallback) {
            fallback = fallback[key];
        } else {
            fallback = undefined;
        }
    }

    let result = (typeof current === "string" ? current : typeof fallback === "string" ? fallback : keyPath);

    if (params) {
        Object.entries(params).forEach(([paramKey, paramValue]) => {
            result = result.replace(new RegExp(`{${paramKey}}`, "g"), String(paramValue));
        });
    }

    return result;
}

/**
 * React hook to access translations and switch application language.
 */
export function useTranslation() {
    const page = usePage();
    const serverLocale = (page.props.locale as Locale) || "en";
    const availableLocales = (page.props.locales as Record<string, string>) || {
        en: "English",
        de: "Deutsch",
    };

    const t = (keyPath: string, params?: Record<string, string | number>): string => {
        return getTranslation(keyPath, serverLocale, params);
    };

    const changeLanguage = (newLocale: Locale) => {
        if (newLocale === serverLocale) return;

        // Post to backend locale route which updates session and sets 1-year unencrypted cookie
        router.post(
            "/locale",
            { locale: newLocale },
            {
                preserveScroll: true,
                preserveState: false,
            }
        );
    };

    return {
        t,
        locale: serverLocale,
        locales: availableLocales,
        changeLanguage,
        isGerman: serverLocale === "de",
        isEnglish: serverLocale === "en",
    };
}
